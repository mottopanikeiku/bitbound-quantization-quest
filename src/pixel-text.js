const GLYPHS = new Map(
  Object.entries(ROWS).map(([letter, rows]) => [
    letter,
    rows.flatMap((row, y) =>
      [...row].flatMap((bit, x) => (bit === "1" ? [[x, y]] : [])),
    ),
  ]),
);
export function textWidth(value, scale = 1) {
  return String(value).length * 6 * scale - scale;
}
export function text(ctx, value, x, y, scale = 1, color = "#fff0c9") {
  const s = Math.max(1, Math.trunc(scale));
  ctx.fillStyle = color;
  const string = String(value)
    .toUpperCase()
    .replaceAll("·", ".")
    .replaceAll("…", "...");
  for (let i = 0; i < string.length; i++)
    for (const [gx, gy] of GLYPHS.get(string[i]) ?? GLYPHS.get("?"))
      ctx.fillRect(
        Math.round(x) + (i * 6 + gx) * s,
        Math.round(y) + gy * s,
        s,
        s,
      );
}
export function centered(ctx, value, y, scale = 1, color) {
  text(ctx, value, (480 - textWidth(value, scale)) / 2, y, scale, color);
}
export function wrapped(
  ctx,
  value,
  x,
  y,
  width,
  scale = 1,
  color,
  lineGap = 4,
) {
  const words = String(value).split(/\s+/);
  let line = "";
  let top = y;
  for (const word of words) {
    if (line && textWidth(`${line} ${word}`, scale) > width) {
      text(ctx, line, x, top, scale, color);
      top += 7 * scale + lineGap;
      line = word;
    } else line += `${line ? " " : ""}${word}`;
  }
  if (line) text(ctx, line, x, top, scale, color);
  return top + 7 * scale;
}
export function panel(
  ctx,
  x,
  y,
  width,
  height,
  fill = "#203747",
  border = "#f7e9ba",
) {
  ctx.fillStyle = "#0d1e29";
  ctx.fillRect(x + 2, y + 2, width, height);
  ctx.fillStyle = border;
  ctx.fillRect(x, y, width, height);
  ctx.fillStyle = fill;
  ctx.fillRect(x + 2, y + 2, width - 4, height - 4);
}
