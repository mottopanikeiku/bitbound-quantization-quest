// Original Bitbound music: sixteenth-note scores, composed for this game.
// The island's D–F#–A / B–A–F# hook becomes a minor battle call and a quiet finale.
// Written A/B phrases, breathing space and scored turnarounds keep the loops musical.
const PITCHES = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };
const pitch = (name) =>
  (Number(name.at(-1)) + 1) * 12 +
  PITCHES[name[0]] +
  (name[1] === "#" ? 1 : name[1] === "b" ? -1 : 0);
const frequency = (note) => 440 * 2 ** ((note - 69) / 12);

function compose({
  bpm,
  chords,
  melody,
  bass,
  arp,
  drums,
  fill = [],
  variations = {},
  lead = "square",
  leadLevel = 0.076,
  arpLevel = 0.027,
  cutoff = 4600,
  pad = false,
}) {
  const stepSeconds = 60 / bpm / 4;
  const steps = Array.from({ length: chords.length * 16 }, () => []);
  const tone = (step, note, length, wave, level, gate = 0.86) => {
    steps[step].push({
      voice: "tone",
      frequency: frequency(note),
      duration: length * stepSeconds * gate,
      wave,
      level,
    });
  };
  chords.forEach(([rootName, ...chordNames], bar) => {
    const root = pitch(rootName);
    const chord = chordNames.map(pitch);
    const start = bar * 16;
    const part = variations[bar] ?? {};
    for (const [step, note, length, accent = 1] of melody[bar]) {
      tone(
        start + step,
        pitch(note),
        length,
        lead,
        (part.leadLevel ?? leadLevel) * accent,
      );
    }
    for (const [step, interval, length] of part.bass ?? bass) {
      tone(start + step, root + interval, length, "triangle", 0.145, 0.9);
    }
    const arpeggio = part.arp ?? arp;
    arpeggio.forEach((chordIndex, index) => {
      if (chordIndex !== null) {
        tone(
          start + index * (16 / arpeggio.length),
          chord[chordIndex],
          16 / arpeggio.length,
          "square",
          part.arpLevel ?? arpLevel,
          0.65,
        );
      }
    });
    for (const [step, kind, level = 1] of part.drums ?? drums)
      steps[start + step].push({ voice: kind, level });
    for (const [step, kind, level = 1] of part.fill ??
      (bar % 4 === 3 ? fill : [])) {
      steps[start + step].push({ voice: kind, level });
    }
    if (pad) {
      tone(start, chord[0], 16, "triangle", 0.026, 0.96);
      tone(start, chord[1], 16, "triangle", 0.02, 0.96);
    }
  });
  return { bpm, stepSeconds, steps, cutoff };
}

